"""szsdlc init: a new project, here or wherever the backend keeps it."""

from __future__ import annotations

import os
from dataclasses import dataclass
from pathlib import Path

from .. import config as config_module
from ..errors import BadInput
from ._paths import relative
from ._registry import operation
from ._types import Data


STARTER_CONFIG = """\
# szsdlc project configuration.
#
# This file is deep-merged over the built-in defaults, so everything below is
# optional and an empty file is already a valid project. Adjust one flag:
#
#   entity_types: {{spike: {{persistent: true}}}}
#
# drop a type you do not want (`entity_types: {{spike: null}}`), or replace a
# whole section outright (`entity_types: {{_replace: true, ...}}`).
project:
  name: {name}
"""


#: Heads the lines `init` adds to `.gitattributes`.
GITATTRIBUTES_NOTE = ("# Generated by szsdlc: keep LF on every checkout, "
                      "so generated files match their hashes.")


def attribute_pattern(path: str) -> str:
    """`path` as a gitattributes pattern matching exactly that file.

    Wildcards are escaped so they match themselves. A path git would split at
    whitespace, or read as a comment (`#`) or a negation (`!`), is C-quoted,
    which git reads in a pattern that starts with a double quote.
    """
    literal = "".join("\\" + ch if ch in "\\*?[" else ch for ch in path)
    if any(ch.isspace() for ch in literal) or literal[:1] in ('"', "#", "!"):
        return '"' + literal.replace("\\", "\\\\").replace('"', '\\"') + '"'
    return literal


def gitattributes_lines(config) -> list[str]:
    """What keeps a project's generated files LF on every checkout (WI-0074).

    Git for Windows converts LF to CRLF on checkout by default
    (`core.autocrlf=true`). szsdlc compares generated files as LF text either
    way; this keeps the files themselves byte-identical to what was rendered.
    Paths are relative to the project sdlc root, where the file goes; config
    already refuses an output that escapes it.
    """
    root = config.root
    lines = [f"{attribute_pattern(relative(root, config.views_dir))}/** text eol=lf"]
    lines += [f"{attribute_pattern(relative(root, config.record_path(name)))} text eol=lf"
              for name in config.records]
    return lines


def write_gitattributes(config) -> Path | None:
    """Add the lines `.gitattributes` lacks; never replace what is there.

    Returns the file when it was written, None when nothing was. Best effort:
    a `.gitattributes` that is a symlink is left alone (it may point outside
    the project), and one that cannot be read or written is skipped, because
    the lines are a convenience and a failed `init` cannot be rerun. The
    replacement is written beside it and moved into place, so a crash never
    leaves it half-written.
    """
    path = config.root / ".gitattributes"
    if path.is_symlink():
        return None
    try:
        existing = path.read_text(encoding="utf-8") if path.is_file() else ""
    except (OSError, UnicodeDecodeError):
        return None
    have = set(existing.splitlines())
    missing = [line for line in gitattributes_lines(config) if line not in have]
    if not missing:
        return None
    head = existing if not existing or existing.endswith("\n") else existing + "\n"
    note = [] if GITATTRIBUTES_NOTE in have else [GITATTRIBUTES_NOTE]
    staged = path.with_name(".gitattributes.szsdlc-tmp")
    try:
        staged.write_bytes((head + "\n".join(note + missing) + "\n").encode("utf-8"))
        os.replace(staged, path)
    except OSError:
        staged.unlink(missing_ok=True)
        return None
    return path


@dataclass(frozen=True)
class InitParams(Data):
    name: str | None = None


@dataclass(frozen=True)
class InitResult(Data):
    root: str
    #: What was made, relative to the root: the config, then each directory.
    created: tuple[str, ...]


@operation("init", params=InitParams, result=InitResult, kind="mutation",
           interfaces=frozenset({"cli"}), loads=False)
def init(params: InitParams, where: str | None) -> InitResult:
    from .. import backend as backend_module
    from ..roadmap import Roadmap

    # With a backend in effect the project goes wherever it keeps it, never
    # into the directory the command was run from.
    root = backend_module.project_sdlc_root(where) or Path(where or Path.cwd()).resolve()
    config_path = config_module.config_path_for(root)
    if config_path.exists():
        raise BadInput(
            f"{config_path} already exists.",
            fix="szsdlc context",
        )

    config_path.parent.mkdir(parents=True, exist_ok=True)
    config_path.write_bytes(STARTER_CONFIG.format(name=params.name or root.name).encode("utf-8"))

    config = config_module.load(root)
    created = [config_path]
    for entity_type in config.entity_types.values():
        directory = config.dir_for(entity_type)
        directory.mkdir(parents=True, exist_ok=True)
        created.append(directory)
    for directory in (config.roadmaps_dir, config.views_dir, config.records_dir,
                      config.standards_dir, config.templates_dir):
        directory.mkdir(parents=True, exist_ok=True)
        created.append(directory)
    for name in config.roadmaps:
        roadmap = Roadmap.load(config, name)
        roadmap.save()
        created.append(roadmap.path)
    attributes = write_gitattributes(config)
    if attributes is not None:
        created.append(attributes)
    return InitResult(str(root), tuple(relative(root, path) for path in created))
