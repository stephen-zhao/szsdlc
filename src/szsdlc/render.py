"""Rendering: every index, board, register and back-link, generated from source.

`render` is deliberately **permissive**. It must succeed against a broken graph,
because intermediate states are legitimately invalid — an entity exists before
it is linked, is linked before it is scheduled — and because views are most
needed exactly when something is wrong. Rendering asks only "can I load and
draw this?"; `validate` asks "is this project coherent?".

That is why a dangling reference renders as `WI-0420 (missing)` and an
unparseable file appears in the view with its path. Dropping broken edges would
let `render` conceal precisely what `validate` exists to surface.

There is no `--check` flag. Staleness is a `validate` rule implemented with the
:func:`compare` primitive below, so CI and pre-commit ask one question, not two.
"""

from __future__ import annotations

import datetime as dt
import hashlib
import json
import traceback
from dataclasses import dataclass
from importlib import resources
from pathlib import Path
from typing import Any

import jinja2
import yaml
from jsonschema import Draft202012Validator

from .config import Config
from .context import captured_on, first_unchecked
from .errors import BadInput
from .graph import Graph
from .model import EntityStore
from .roadmap import Roadmap, load_all as load_roadmaps
from .text import clip

BANNER = "<!-- GENERATED by szsdlc — do not edit; edit the source and rerun `szsdlc render`. -->"
HASH_PREFIX = "<!-- content-hash: "
HASH_SUFFIX = " -->"


@dataclass(frozen=True)
class Rendered:
    """One generated file, in memory. Nothing here has touched the disk yet."""

    name: str
    path: Path
    body: str

    @property
    def content(self) -> str:
        """Banner, hash, then the body.

        The hash digests the *rendered body*, which is what makes a hand-edit
        distinguishable from staleness: a mismatch means somebody typed into a
        generated file, while a matching hash over different content means the
        sources moved on. A hash of the inputs could only ever tell you the
        second thing.
        """
        # LF, like everything read back to be compared: a template or data
        # value carrying \r must not make a file it just wrote read as edited.
        body = normalize_newlines(self.body)
        digest = hashlib.sha256(body.encode("utf-8")).hexdigest()[:16]
        return f"{BANNER}\n{HASH_PREFIX}sha256:{digest}{HASH_SUFFIX}\n\n{body}"

    def matches_disk(self) -> bool:
        if not self.path.is_file():
            return False
        return read_generated(self.path) == self.content

    def has_been_hand_edited(self) -> bool:
        """Whether the file this would overwrite no longer matches its own hash.

        Returns:
            False when the file does not exist yet.
        """
        if not self.path.is_file():
            return False
        return hand_edited(read_generated(self.path))

    def write(self) -> None:
        self.path.parent.mkdir(parents=True, exist_ok=True)
        self.path.write_bytes(self.content.encode("utf-8"))


def normalize_newlines(text: str) -> str:
    r"""`\r\n` and a lone `\r` as `\n`.

    A generated file is always compared as LF text: git for Windows checks
    files out with CRLF by default (`core.autocrlf=true`), and a checkout is
    not an edit. The content hash is defined over the LF body, so a file keeps
    matching whichever platform rendered or checked it out (WI-0074).
    """
    return text.replace("\r\n", "\n").replace("\r", "\n")


def read_generated(path: Path) -> str:
    """A generated file as text to compare: decoded, with its line endings normalised."""
    return normalize_newlines(path.read_bytes().decode("utf-8", "replace"))


def is_generated(text: str) -> bool:
    """Does this content carry the generated banner? Used by the edit hook."""
    return text.lstrip().startswith(BANNER)


def stored_hash(text: str) -> str | None:
    for line in normalize_newlines(text).split("\n")[:5]:
        if line.startswith(HASH_PREFIX) and line.endswith(HASH_SUFFIX):
            return line[len(HASH_PREFIX):-len(HASH_SUFFIX)]
    return None


def hand_edited(text: str) -> bool:
    """True when a generated file's body no longer matches its own hash."""
    text = normalize_newlines(text)
    declared = stored_hash(text)
    if declared is None:
        return False
    _, _, body = text.partition("\n\n")
    actual = "sha256:" + hashlib.sha256(body.encode("utf-8")).hexdigest()[:16]
    return declared != actual


class Renderer:
    """Renders every configured view and record from one loaded graph."""

    def __init__(self, config: Config, store: EntityStore, graph: Graph,
                 roadmaps: dict[str, Roadmap] | None = None):
        self.config = config
        self.store = store
        self.graph = graph
        self.roadmaps = roadmaps if roadmaps is not None else load_roadmaps(config)
        self.environment = self._environment()

    def _environment(self) -> jinja2.Environment:
        bundled = resources.files("szsdlc").joinpath("templates")
        environment = jinja2.Environment(
            loader=jinja2.ChoiceLoader([
                # A project override wins; the bundled default is the fallback.
                jinja2.FileSystemLoader(str(self.config.templates_dir)),
                jinja2.FileSystemLoader(str(bundled)),
            ]),
            autoescape=False,
            trim_blocks=True,
            lstrip_blocks=True,
            keep_trailing_newline=True,
            undefined=jinja2.StrictUndefined,
        )
        environment.globals.update(
            config=self.config,
            store=self.store,
            graph=self.graph,
            roadmaps=self.roadmaps,
            entities=sorted(self.store, key=lambda e: (e.id.prefix, e.id.number)),
            unparseable=self.store.unparseable,
            duplicates=self.store.duplicates,
            types_with=self.config.types_with,
            of_type=self.store.of_type,
            derived=self.graph.derived,
            children=self.graph.children,
            sources=self.graph.sources,
            targets=self.graph.targets,
            # No clock. Every template renders into a content-hashed file, so a
            # global that reads today's date is a file that changes on its own
            # overnight: `render` rewrites it, `validate` calls it stale, and the
            # Stop hook blocks a session over a number nobody wrote. Dates are
            # facts about an entity and belong here; ages are facts about now
            # and belong in command output, which is read once and discarded.
            captured_on=captured_on,
            next_task=first_unchecked,
            relative=lambda path: self._relative(path),
        )
        # A title may be derived from body text, so it is exactly as long as
        # whoever captured the thought felt like being. Unclipped, one such
        # entity turns a markdown table into a single unreadable row.
        environment.filters["clip"] = clip
        return environment

    def _relative(self, path: Path | str) -> str:
        try:
            return Path(path).resolve().relative_to(self.config.root).as_posix()
        except ValueError:
            return str(path)

    # -- views --------------------------------------------------------------

    def _owned(self, filename: str | None) -> Path | None:
        """`filename` as a path inside the project's templates, or None."""
        if not filename:
            return None
        try:
            path = Path(filename).resolve()
            path.relative_to(self.config.templates_dir.resolve())
        except (OSError, ValueError):
            return None
        return path

    def _render(self, template_name: str, **context: Any) -> str:
        """Render one template; a fault in the project's own template is a finding.

        Ownership is decided by where the fault happened, not by what it is. A
        traceback that passes through a file under the project's templates
        directory is the project's to fix, so it becomes `BadInput` naming that
        file and line. The same exception raised inside a bundled template is
        a framework bug, and is re-raised so it is reported as one.
        """
        try:
            template = self.environment.get_template(template_name)
            return template.render(**context)
        except jinja2.TemplateNotFound as exc:
            missing = exc.name or template_name
            target = self._relative(self.config.templates_dir / missing)
            raise BadInput(f"template {missing} does not exist.",
                           fix=f"create {target}") from None
        except jinja2.TemplateSyntaxError as exc:
            path = self._owned(exc.filename)
            if path is None:
                raise
            raise self._fault(path, exc.lineno, exc.message or str(exc)) from None
        except Exception as exc:  # noqa: BLE001 — re-raised unless the project owns it
            for frame, line in reversed(list(traceback.walk_tb(exc.__traceback__))):
                path = self._owned(frame.f_code.co_filename)
                if path is not None:
                    raise self._fault(path, line, str(exc) or type(exc).__name__) from None
            raise

    def _fault(self, path: Path, line: int | None, message: str) -> BadInput:
        where = self._relative(path) + (f":{line}" if line else "")
        return BadInput(f"template {where}: {message.rstrip('.')}.",
                        fix=f"correct {self._relative(path)}")

    def view(self, name: str) -> Rendered:
        spec = self.config.views[name]
        body = self._render(spec.template, view=spec, name=name)
        return Rendered(name=name, path=self.config.view_path(name), body=body)

    def record(self, name: str) -> Rendered:
        """A project-defined dataset rendered through its own template.

        The generic mechanism for any tracked table a project needs. Nothing
        project-specific ships built in; this is how it gets added without
        touching the framework.
        """
        spec = self.config.records[name]
        data_path = self.config.root / spec.data
        if not data_path.is_file():
            raise BadInput(
                f"record {name!r}: {self._relative(data_path)} does not exist.",
                fix=f"create {self._relative(data_path)}",
            )

        try:
            data = yaml.safe_load(data_path.read_text(encoding="utf-8"))
        except yaml.YAMLError as exc:
            problem = getattr(exc, "problem", None) or "invalid YAML"
            raise BadInput(
                f"record {name!r}: {self._relative(data_path)}: {problem}.",
                fix=f"correct {self._relative(data_path)}",
            ) from None

        data = _jsonish(data)

        if spec.schema:
            schema_path = self.config.root / spec.schema
            try:
                schema = json.loads(schema_path.read_text(encoding="utf-8"))
            except FileNotFoundError:
                raise BadInput(
                    f"record {name!r}: {self._relative(schema_path)} does not exist.",
                    fix=f"create {self._relative(schema_path)}, or remove records.{name}.schema",
                ) from None
            except json.JSONDecodeError as exc:
                raise BadInput(
                    f"record {name!r}: {self._relative(schema_path)}:{exc.lineno}: "
                    f"not valid JSON ({exc.msg}).",
                    fix=f"correct {self._relative(schema_path)}",
                ) from None
            errors = sorted(Draft202012Validator(schema).iter_errors(data),
                            key=lambda e: list(e.absolute_path))
            if errors:
                where = ".".join(str(p) for p in errors[0].absolute_path) or "(root)"
                raise BadInput(
                    f"record {name!r}: {where}: {errors[0].message}",
                    fix=f"correct {self._relative(data_path)}",
                )

        body = self._render(spec.template, record=spec, name=name, data=data)
        return Rendered(name=name, path=self.config.record_path(name), body=body)

    def all(self) -> list[Rendered]:
        """Everything generated, skipping records that cannot be built.

        A broken record is a fact about the *project*, so it becomes a
        validate finding rather than an exception. Raising here instead would
        let one malformed YAML file take down `context` — and `context` is the
        SessionStart payload, so a stray colon in a hand-authored dataset would
        silently cost the model everything it knows about the work.
        """
        rendered = []
        for name in self.config.views:
            try:
                rendered.append(self.view(name))
            except BadInput:
                continue
        for name in self.config.records:
            try:
                rendered.append(self.record(name))
            except BadInput:
                continue
        return rendered

    def view_problems(self) -> list[tuple[str, BadInput]]:
        """Each view whose project template cannot be rendered, and why."""
        problems = []
        for name in self.config.views:
            try:
                self.view(name)
            except BadInput as exc:
                problems.append((name, exc))
        return problems

    def record_problems(self) -> list[BadInput]:
        """Why each unbuildable record could not be built. Used by `validate`,
        which is the command whose job it is to say so."""
        problems = []
        for name in self.config.records:
            try:
                self.record(name)
            except BadInput as exc:
                problems.append(exc)
        return problems


def _jsonish(value: Any) -> Any:
    """Fold YAML's own scalar types down to what JSON Schema can validate.

    `last_calibrated: 2026-05-02` is a `datetime.date` to a YAML parser and a
    string to every schema anybody would write for it, so the most obvious
    field a record can hold — a date — failed validation with a message
    blaming the author and quoting a Python repr back at them. Dates become
    ISO 8601 strings, which is both what `format: date` expects and what the
    template would have rendered anyway.

    Applied before validation *and* before rendering, so the schema a project
    writes describes the same data its template receives.
    """
    if isinstance(value, dict):
        return {key: _jsonish(item) for key, item in value.items()}
    if isinstance(value, (list, tuple)):
        return [_jsonish(item) for item in value]
    if isinstance(value, (dt.date, dt.datetime, dt.time)):
        return value.isoformat()
    return value


def compare(rendered: list[Rendered]) -> list[Rendered]:
    """Which generated files would differ from what is on disk.

    The primitive `render` uses to avoid pointless writes and `validate` borrows
    for its staleness rule — one implementation, so the two can never disagree
    about what "stale" means.
    """
    return [item for item in rendered if not item.matches_disk()]


def render(config: Config, store: EntityStore, graph: Graph,
         roadmaps: dict[str, Roadmap] | None = None, *,
         should_keep_hand_edited: bool = False) -> list[Rendered]:
    """Regenerate everything, writing only what changed. Never validates.

    Args:
        config: The loaded project config.
        store: Entities to render from.
        graph: Relations and derived attributes to render from.
        roadmaps: Loaded roadmaps; loaded from disk when None.
        should_keep_hand_edited: Skip files whose body no longer matches their
            own hash. Set by the turn-end hook, which nobody asked for and
            which cannot recover text it overwrites; `szsdlc render` leaves it
            unset and overwrites.

    Returns:
        The files actually written.
    """
    renderer = Renderer(config, store, graph, roadmaps)
    items = renderer.all()
    if should_keep_hand_edited:
        items = [item for item in items if not item.has_been_hand_edited()]
    changed = compare(items)
    for item in changed:
        item.write()
    return changed
